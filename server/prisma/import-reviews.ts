async function main() {
  const questSlug = 'silent-hill';
  
  const quest = await prisma.quest.findUnique({
    where: { slug: questSlug }
  });

  if (!quest) {
    console.error(`Quest with slug "${questSlug}" not found in DB!`);
    return;
  }

  console.log(`Found quest: ${quest.name} (ID: ${quest.id})`);
  
  // Create reviews
  let addedCount = 0;
  for (const review of reviews) {
    // Check if review already exists to avoid duplicates
    const existing = await prisma.review.findFirst({
      where: {
        questId: quest.id,
        author: review.author,
        text: review.text,
      }
    });

    if (!existing) {
      await prisma.review.create({
        data: {
          questId: quest.id,
          author: review.author,
          rating: review.rating,
          text: review.text,
          status: 'APPROVED',
          createdAt: new Date(review.date),
        }
      });
      addedCount++;
    }
  }
  
  console.log(`✅ Added ${addedCount} new reviews for ${quest.name}.`);

  // Recalculate quest rating
  const allReviews = await prisma.review.findMany({
    where: { questId: quest.id, status: 'APPROVED' }
  });

  if (allReviews.length > 0) {
    const totalRating = allReviews.reduce((sum, r) => sum + r.rating, 0);
    const newRating = Number((totalRating / allReviews.length).toFixed(1));
    
    await prisma.quest.update({
      where: { id: quest.id },
      data: {
        rating: newRating,
        reviewCount: allReviews.length
      }
    });
    console.log(`✅ Updated quest rating to ${newRating} based on ${allReviews.length} reviews.`);
  }
}

main()
  .catch(e => console.error(e))
  .finally(() => prisma.$disconnect());
